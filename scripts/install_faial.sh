#!/bin/bash
# Fetch the prebuilt faial bundle (faial-cost aka pico, cu-to-json, libz3) and
# expose faial-cost / faial-drf on PATH without Docker.
#
# The bundled binaries have no rpath and faial-cost shells out to cu-to-json via
# PATH, so we install thin wrappers that set LD_LIBRARY_PATH and PATH first.
#
# Env overrides:
#   FAIAL_PREFIX  where the bundle is extracted (default ~/.local/share/faial)
#   BIN_DIR       where the wrappers go          (default ~/.local/bin)
#
# Usage: scripts/install_faial.sh [--force]
#   --force  reinstall even if faial-cost is already available
set -euo pipefail

FAIAL_PREFIX="${FAIAL_PREFIX:-$HOME/.local/share/faial}"
BIN_DIR="${BIN_DIR:-$HOME/.local/bin}"
TOOLS=(faial-cost faial-drf)

die() {
  >&2 echo "error: $*"
  exit 1
}

force=0
case "${1:-}" in
  --force) force=1 ;;
  "") ;;
  *) die "unknown argument: $1 (usage: $0 [--force])" ;;
esac

existing="$(command -v faial-cost || true)"
if [ -z "$existing" ] && [ -x "$BIN_DIR/faial-cost" ]; then
  existing="$BIN_DIR/faial-cost"
fi
if [ -n "$existing" ] && [ "$force" -eq 0 ]; then
  echo "faial-cost is already installed at $existing; rerun with --force to reinstall"
  exit 0
fi

case "$(uname -s)-$(uname -m)" in
  Linux-x86_64)
    job=bundle-lin
    libvar=LD_LIBRARY_PATH
    ;;
  Darwin-arm64)
    job=bundle-mac
    libvar=DYLD_LIBRARY_PATH
    ;;
  *)
    die "no prebuilt faial bundle for $(uname -s)/$(uname -m); use the Dockerfile instead"
    ;;
esac
url="https://gitlab.com/umb-svl/faial/-/jobs/artifacts/main/raw/bundle/faial.tar.bz2?job=$job"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

echo "Downloading faial bundle ($job)..."
if command -v curl > /dev/null; then
  curl -fL --progress-bar "$url" -o "$tmp/faial.tar.bz2"
elif command -v wget > /dev/null; then
  wget -nv "$url" -O "$tmp/faial.tar.bz2"
else
  die "need curl or wget"
fi

mkdir "$tmp/faial"
tar xjf "$tmp/faial.tar.bz2" -C "$tmp/faial"
[ -x "$tmp/faial/bin/faial-cost" ] || die "bundle is missing bin/faial-cost"

echo "Installing bundle to $FAIAL_PREFIX"
rm -rf "$FAIAL_PREFIX"
mkdir -p "$(dirname "$FAIAL_PREFIX")"
mv "$tmp/faial" "$FAIAL_PREFIX"

mkdir -p "$BIN_DIR"
for tool in "${TOOLS[@]}"; do
  cat > "$BIN_DIR/$tool" << EOF
#!/bin/bash
# Generated by gasp scripts/install_faial.sh
export PATH="$FAIAL_PREFIX/bin:\$PATH"
export $libvar="$FAIAL_PREFIX/lib\${$libvar:+:\$$libvar}"
exec "$FAIAL_PREFIX/bin/$tool" "\$@"
EOF
  chmod +x "$BIN_DIR/$tool"
  echo "Installed $BIN_DIR/$tool"
done

# libgmp is the one runtime dependency not shipped in the bundle
if [ "$job" = bundle-lin ]; then
  missing="$(LD_LIBRARY_PATH="$FAIAL_PREFIX/lib" ldd "$FAIAL_PREFIX/bin/faial-cost" | awk '/not found/ {print $1}')"
  if [ -n "$missing" ]; then
    echo "warning: missing shared libraries: $missing"
    echo "         libgmp.so.10 comes from e.g. 'sudo apt install libgmp10'"
  fi
fi

if "$BIN_DIR/faial-cost" --help > /dev/null 2>&1; then
  echo "faial-cost OK"
else
  echo "warning: '$BIN_DIR/faial-cost --help' failed"
fi

case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) echo "note: $BIN_DIR is not on PATH; add it to use faial-cost from gasp" ;;
esac
